账号来源：云端书院的账号不能自己注册。所有师生账号由学校或学院的管理员在管理后台统一导入或新增，账号以学号（教师为工号）作为登录名。如果你用微信打开小程序后提示需要绑定，说明系统里还没有你的账号，或者你的学号还没有被导入，请联系学院管理员。

有两种登录方式：

第一种是微信登录并绑定学号。点击登录后授权微信，如果这个微信还没有绑定过账号，会提示你输入学号和密码完成绑定。绑定成功后，以后打开小程序会自动登录，不用再输密码。一个学号只能绑定一个微信；如果提示「该学号已绑定其他微信」，需要联系管理员解绑。

第二种是直接用学号和密码登录。在登录页选择学号登录，输入学号与密码即可。学号登录后，也可以在个人资料页把当前微信绑定上去，之后就能免密登录。

首次登录必须修改密码。管理员导入账号时会设置初始密码，第一次登录后系统会要求你修改，改完才能正常使用。新密码要求：至少 8 位，必须同时包含字母和数字，并且不能与原密码相同。

忘记密码怎么办：小程序没有自助找回密码的功能，请联系学院管理员在管理后台重置。管理员重置后会生成一个临时密码，你用临时密码登录后系统会再次要求你修改。

登录状态会保持一段时间，过期后需要重新登录。如果你在个人中心修改了密码，其他设备上的登录状态会立即失效，需要用新密码重新登录。

账号被停用：如果提示账号已停用或无法登录，可能是管理员停用了该账号，或者该账号已被清退。请联系学院管理员确认。

哪些功能必须登录：收藏、点赞、报名活动、下载资源、记录课程学习进度、获得积分与徽章、使用书院助手智能问答、查看消息中心、提交意见反馈。浏览动态、展馆、课程列表和详情不需要登录。

退出登录：在个人中心可以退出当前账号。退出后收藏、报名等个人数据不会丢失，重新登录即可看到。

