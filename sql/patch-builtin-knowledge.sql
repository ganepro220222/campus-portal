FROM `knowledge_doc` d
LEFT JOIN `knowledge_chunk` c ON c.`doc_id` = d.`id`
WHERE d.`file_url` LIKE 'builtin://%'
GROUP BY d.`id`, d.`title`, d.`chunk_count`, d.`status`;
